#!/usr/bin/env node
/**
 * probe-licensed-content.mjs
 *
 * Empirical check of what `contentDetails.licensedContent` actually reflects,
 * and whether it matches the product claim ("already audio fingerprinted /
 * registered copyright work").
 *
 * Usage:
 *   YT_API_KEY=... node scripts/probe-licensed-content.mjs
 *
 * Costs: search.list = 100 units each, videos.list = 1 unit per call.
 * The default 12-query run costs ~1,200 units against the 10,000/day quota.
 *
 * NOTE: never commit a real key. This script only reads it from the env.
 */

const API_KEY = process.env.YT_API_KEY;
if (!API_KEY) {
  console.error("Set YT_API_KEY in the environment. Do not commit it.");
  process.exit(1);
}

const API = "https://youtube.googleapis.com/youtube/v3";

// A deliberately mixed set: the tool's real use case (music / reuploads) plus
// clearly non-music categories, to expose false positives.
const QUERIES = [
  "chopped n skrewed",          // the README screenshot query
  "official music video",
  "daft punk around the world",
  "billie jean",
  "top songs 2024",
  "instrumental",
  "news report",                // non-music control
  "nba highlights",             // non-music control
  "space documentary",          // non-music control
  "movie trailer official",     // non-music control
  "cooking recipe",             // non-music control
  "math lecture",               // non-music control
];

const CATEGORY_NAMES = {
  "1": "Film & Animation", "2": "Autos & Vehicles", "10": "Music",
  "15": "Pets & Animals", "17": "Sports", "18": "Short Movies",
  "19": "Travel & Events", "20": "Gaming", "21": "Videoblogging",
  "22": "People & Blogs", "23": "Comedy", "24": "Entertainment",
  "25": "News & Politics", "26": "Howto & Style", "27": "Education",
  "28": "Science & Technology", "29": "Nonprofits & Activism",
};

async function api(path, params) {
  const url = new URL(`${API}/${path}`);
  for (const [k, v] of Object.entries(params)) url.searchParams.set(k, v);
  url.searchParams.set("key", API_KEY);
  const res = await fetch(url);
  const body = await res.json();
  if (!res.ok) {
    throw new Error(`${path} failed (${res.status}): ${body?.error?.message || res.statusText}`);
  }
  return body;
}

function chunk(arr, n) {
  const out = [];
  for (let i = 0; i < arr.length; i += n) out.push(arr.slice(i, i + n));
  return out;
}

/** Heuristics used only for reporting, not for the product decision. */
function isPartnerChannel(title) {
  return /VEVO$/i.test(title) || /-\s*Topic$/i.test(title) || /\bTopic$/i.test(title) || /Music$/i.test(title);
}
function hasDistributionAttribution(description = "") {
  return (
    description.startsWith("Provided to YouTube by") ||
    description.includes("Auto-generated by YouTube") ||
    description.includes("Licensed to YouTube by")
  );
}

const rows = [];

for (const q of QUERIES) {
  let search;
  try {
    search = await api("search", { part: "snippet", type: "video", maxResults: "25", q });
  } catch (err) {
    console.error(`search "${q}" skipped: ${err.message}`);
    continue;
  }
  const ids = (search.items || []).map((i) => i.id?.videoId).filter(Boolean);
  if (!ids.length) continue;

  for (const group of chunk(ids, 50)) {
    const vids = await api("videos", { part: "contentDetails,snippet", id: group.join(",") });
    for (const it of vids.items || []) {
      const s = it.snippet;
      const desc = s.description || "";
      rows.push({
        query: q,
        id: it.id,
        licensed: it.contentDetails?.licensedContent === true,
        categoryId: s.categoryId,
        channel: s.channelTitle,
        title: s.title,
        partnerChannel: isPartnerChannel(s.channelTitle),
        distributed: hasDistributionAttribution(desc),
      });
    }
  }
}

// ---- Report ----
const pct = (n, d) => (d === 0 ? "  n/a" : `${((100 * n) / d).toFixed(1).padStart(5)}%`);

console.log(`\nSampled ${rows.length} unique videos across ${QUERIES.length} queries.\n`);

console.log("Per-category: how often licensedContent is true");
console.log(`${"category".padEnd(24)}${"n".padStart(5)}${"licensed=true".padStart(15)}`);
const byCat = new Map();
for (const r of rows) {
  if (!byCat.has(r.categoryId)) byCat.set(r.categoryId, []);
  byCat.get(r.categoryId).push(r);
}
for (const [cat, rs] of [...byCat.entries()].sort((a, b) => b[1].length - a[1].length)) {
  const t = rs.filter((r) => r.licensed).length;
  const name = `${CATEGORY_NAMES[cat] || "Unknown"} (${cat})`;
  console.log(`${name.padEnd(24)}${String(rs.length).padStart(5)}${`${t} (${pct(t, rs.length).trim()})`.padStart(15)}`);
}

const licensed = rows.filter((r) => r.licensed);
const musicCat = rows.filter((r) => r.categoryId === "10");
const nonMusicCat = rows.filter((r) => r.categoryId !== "10");

console.log("\nHeadline checks");
console.log(`  licensedContent=true, total          : ${licensed.length}/${rows.length}`);
console.log(`  ...of those, categoryId != 10 (MUSIC): ${licensed.filter((r) => r.categoryId !== "10").length}  <- badge says MUSIC on non-music`);
console.log(`  categoryId == 10 (Music) licensed rate: ${musicCat.filter((r) => r.licensed).length}/${musicCat.length} (${pct(musicCat.filter((r) => r.licensed).length, musicCat.length).trim()})`);
console.log(`  non-music categories licensed rate    : ${nonMusicCat.filter((r) => r.licensed).length}/${nonMusicCat.length} (${pct(nonMusicCat.filter((r) => r.licensed).length, nonMusicCat.length).trim()})`);
console.log(`  "Provided to YouTube by" (distributed): ${rows.filter((r) => r.distributed).length}`);
console.log(`  of distributed ones, licensed=true    : ${rows.filter((r) => r.distributed && r.licensed).length}/${rows.filter((r) => r.distributed).length || 0}`);

console.log("\nContent-ID-relevant: distributed releases that are NOT flagged (missed by badge)");
for (const r of rows.filter((r) => r.distributed && !r.licensed).slice(0, 10)) {
  console.log(`  cat=${r.categoryId} ${r.channel.slice(0, 22).padEnd(22)} ${r.title.slice(0, 44)}`);
}

console.log("\nFalse positives in the sample: licensed=true, non-music category (badge would say MUSIC)");
for (const r of licensed.filter((r) => r.categoryId !== "10").slice(0, 12)) {
  console.log(`  cat=${r.categoryId} ${r.channel.slice(0, 22).padEnd(22)} ${r.title.slice(0, 44)}`);
}

console.log("\nNon-partner channels that still get a badge (reuploads / UGC)");
for (const r of licensed.filter((r) => !r.partnerChannel && r.categoryId === "10").slice(0, 12)) {
  console.log(`  cat=${r.categoryId} ${r.channel.slice(0, 22).padEnd(22)} ${r.title.slice(0, 44)}`);
}

const out = process.env.OUT_JSON;
if (out) {
  const { writeFileSync } = await import("node:fs");
  writeFileSync(out, JSON.stringify(rows, null, 2));
  console.log(`\nRaw rows written to ${out}`);
}
